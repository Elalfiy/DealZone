export const formatPrice = (amount, language = 'en') => {
  if (!amount && amount !== 0) return language === 'ar' ? 'طلب عرض سعر' : 'Request Quote'
  
  const numAmount = typeof amount === 'number' ? amount : parseFloat(String(amount).replace(/[^0-9.]/g, '') || '0')
  
  if (language === 'ar') {
    return `${numAmount.toLocaleString('ar-EG')} ج.م`
  }
  return `EGP ${numAmount.toLocaleString()}`
}

